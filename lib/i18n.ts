export function translate(lang: Lang, key: MessageKey, vars?: Vars): string {
  const table = lang === "sv" ? sv : en;
  let text: string = table[key] ?? en[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

/** Current language, including outside React (toasts, field errors). */
export function t(key: MessageKey, vars?: Vars): string {
  return translate(useLang.getState().lang, key, vars);
}

export function useT() {
  const lang = useLang((s) => s.lang);
  return useCallback((key: MessageKey, vars?: Vars) => translate(lang, key, vars), [lang]);
}

export function intlLocale(lang: Lang): string {
  return lang === "sv" ? "sv-SE" : "en-US";
}

export function greetingKey(hour = new Date().getHours()): MessageKey {
  if (hour < 12) return "greet.morning";
  if (hour < 17) return "greet.afternoon";
  return "greet.evening";
}

