export function achievementCopy(
  code: string,
  lang: Lang,
  fallback: { title: string; description: string },
): { title: string; description: string } {
  const titleKey = `ach.${code}.title`;
  const bodyKey = `ach.${code}.body`;
  if (!isMessageKey(titleKey) || !isMessageKey(bodyKey)) return fallback;
  return {
    title: translate(lang, titleKey),
    description: translate(lang, bodyKey),
  };
}

function isMessageKey(key: string): key is MessageKey {
  return Object.prototype.hasOwnProperty.call(en, key);
}
